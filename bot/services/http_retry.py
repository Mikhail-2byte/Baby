"""Общая политика повторов для исходящих HTTP-вызовов.

До этого модуля цикл ретраев существовал в двух экземплярах — в `llm.py` и в
`voice.py`, — и совпадали они построчно, вместе с константами и комментариями
к ним. Разошлись бы они молча: правку `TIMEOUT` в одном никто бы не заметил
во втором, а второй — это голос, то есть путь, по которому в проект приходит
самое длинное ожидание.

Модуль чистый: ни aiogram, ни БД. Про `httpx` знает ровно настолько, чтобы
принять готовый клиент и вызвать переданную корутину.

Три величины и их цена. `ATTEMPTS × TIMEOUT` плюс паузы — это верхняя граница
ожидания на **один** вызов: 3 × 60 + 2 + 4 = 186 секунд. Голосовое проходит
через два таких вызова подряд (расшифровка, затем модель), то есть до шести
минут. Отсюда `TOTAL_BUDGET`: сколько бы ни было попыток, дольше него не ждём.
"""

import asyncio
import logging
from collections.abc import Awaitable, Callable
from typing import TypeVar

log = logging.getLogger(__name__)

TIMEOUT = 60.0  # на одну попытку
ATTEMPTS = 3  # первая попытка плюс два ретрая
BACKOFF = 2.0  # секунды перед вторым ретраем, дальше вдвое

# Потолок на весь вызов вместе с ретраями. Человек в чате ждёт ответа, и
# 186 секунд молчания он читает как «бот умер», а не как «провайдер тупит»:
# на живом логе уже виден разбор в 21 секунду, и это была удачная попытка.
#
# Числом, а не «ATTEMPTS × TIMEOUT»: то — верхняя граница арифметики, а это —
# решение о том, сколько ждать не жалко. Исчерпав его, отвечаем как при любом
# другом сбое — то есть уходим на `dateparser`, а не молчим.
#
# 90 секунд хватает на две полные попытки с паузой между ними (60 + 2 + …).
# Третья при полном молчании провайдера не начнётся — и правильно: если две
# минуты не ответили, третья не поможет, а человек всё это время ждёт
TOTAL_BUDGET = 90.0

# Повторять есть смысл только на этих: 429 — занятая квота или бесплатный пул,
# 5xx — сбой на стороне провайдера. На 401/402/404 повтор даст то же самое
RETRY_CODES = frozenset({408, 429, 500, 502, 503, 504})

T = TypeVar("T")


async def with_retries(
    attempt: Callable[[], Awaitable[T | None]],
    *,
    what: str,
    attempts: int = ATTEMPTS,
    budget: float = TOTAL_BUDGET,
) -> T | None:
    """Повторять `attempt`, пока та просит повтора, но не дольше `budget`.

    Контракт `attempt` тот же, что был у `_try_once` в обоих модулях, и менять
    его не надо: `None` — «имеет смысл повторить», всё остальное — результат.
    Пустое значение вызывающий отличает сам (`outcome or None`): для одного
    пустая строка — отказ, для другого могла бы быть валидным ответом.

    Исключений наружу не выпускает — их ловит сама `attempt`, как и раньше.

    Бюджет накрывает **весь** цикл, а не только паузы между попытками, и
    поэтому реализован через `asyncio.timeout`, а не сверкой часов перед сном.
    Проверка «успеем ли поспать» ничего бы не дала: сама попытка длится до
    `TIMEOUT`, и две подряд перевалили бы за бюджет, ни разу его не проверив.

    Обрыв попытки посередине безопасен: `CancelledError` наследуется от
    `BaseException`, а не от `Exception`, поэтому `except Exception` внутри
    `attempt` его не проглотит и соединение закроется как положено.
    """
    try:
        async with asyncio.timeout(budget):
            for number in range(attempts):
                outcome = await attempt()
                if outcome is not None:
                    return outcome
                if number < attempts - 1:
                    await asyncio.sleep(BACKOFF * 2**number)
    except TimeoutError:
        log.warning("%s: не уложились в %.0f с — сдаёмся", what, budget)
    return None
