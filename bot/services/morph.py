"""Морфология для поиска по базе знаний.

FTS5 с токенизатором `unicode61` умеет разбивать русский текст на слова и
приводить регистр, но про склонение не знает ничего. В документе написано
«при грудном вскармливании», человек спрашивает «а вскармливание грудью
это…» — и точного совпадения нет ни одного. Лечится одинаково с обеих
сторон: и в индекс, и в запрос кладутся не слова, а их основы.

**Нормализация берётся та же, что в триаже** — `redflags.normalize`. Две
нормализации в одном проекте неизбежно разойдутся, и тогда поиск начнёт
зависеть от того, через какую дверь вошёл текст. Импорт сюда безопасен:
`redflags` не знает ни про aiogram, ни про базу.

**Выражение для `MATCH` собирается из своих токенов, а не из текста
человека.** Это не гигиена, а условие работоспособности: кавычка, звёздочка,
дефис или слово `AND` внутри вопроса — синтаксис самого FTS5, и вопрос
«а „пустышка“ — это нормально?» не нашёл бы ничего, а упал бы с
`sqlite3.OperationalError` где-то в недрах поиска.

Стеммер — Snowball (`py-rust-stemmers`). Он не словарный и местами грубоват:
«прививка» и «прививок» дают разные основы, потому что беглую гласную
алгоритм не знает. Для поиска это не беда — запрос разворачивается в ИЛИ по
всем основам, и bm25 складывает то, что нашлось.
"""

import re

from py_rust_stemmers import SnowballStemmer

from bot.services.redflags import normalize

# Слово — буквы и цифры подряд. Дефис границей считается намеренно:
# «во-первых» и «103-й» в запросе полезнее двумя токенами, чем одним
_WORD = re.compile(r"[0-9a-zа-я]+")

# Односимвольные токены не несут смысла, но раздувают и индекс, и запрос
MIN_LENGTH = 2

_stemmer = SnowballStemmer("russian")

# Вопросительные слова и модальные связки. Единственный список слов «руками»
# во всём поиске, и он здесь по необходимости: значимость слова мы считаем по
# частоте в документах, а этих слов в документах почти нет — клинические
# рекомендации не задают вопросов, они отвечают. «Сколько» встречается в двух
# фрагментах из восьмисот, то есть выглядит редчайшим термином, и вопрос
# «сколько стоит биткоин» получал на нём полное покрытие.
#
# Список короткий намеренно: сюда попадает только машинерия вопроса, а не
# слова, которые могут что-то значить. Если сомневаешься — не добавляй,
# частотный отсев разберётся сам.
# Словами, а не основами: список читается человеком, а основы у Snowball
# бывают неожиданные («зачем» -> `зач`, «почему» -> `поч`), и написанные
# руками они молча разошлись бы с тем, что стеммер выдаёт на самом деле
QUESTION_WORDS = (
    "сколько", "когда", "как", "какой", "зачем", "почему", "отчего",
    "куда", "где", "кто", "что", "чтобы", "ли", "можно", "нужно", "надо",
    "делать", "бывает", "стоит", "это", "так", "сам",
)


def stems(text: str) -> list[str]:
    """Основы слов текста, в порядке появления, с повторами.

    Повторы не убираем: частота слова в чанке — это ровно то, на чём работает
    bm25. Убрав дубли в индексе, мы бы выключили ранжирование.
    """
    words = [word for word in _WORD.findall(normalize(text)) if len(word) >= MIN_LENGTH]
    if not words:
        return []
    return list(_stemmer.stem_words(words))


QUESTION_STEMS = frozenset(_stemmer.stem_words([normalize(word) for word in QUESTION_WORDS]))


def index_text(text: str) -> str:
    """Строка для записи в `chunks_fts.body`."""
    return " ".join(stems(text))


def match_query(text: str) -> str:
    """Выражение `MATCH` по вопросу человека, или пустая строка.

    Основы соединяются через `OR`, а не через пробел: пробел в FTS5 означает
    `AND`, и вопрос из семи слов нашёл бы только чанк, где есть все семь.
    Каждая основа берётся в кавычки — после этого она для FTS5 просто строка,
    чем бы ни была в исходном тексте.

    Поиск по началу основы, а не по ней целиком. Это не «на всякий случай»:
    Snowball оставляет в русском разные основы у слов одного гнезда —
    «невролога» даёт `невролог`, а «неврологических» уже `неврологическ», и
    без звёздочки документ, где написано только второе, по вопросу про
    невролога не находится вовсе. Измерено оценочным набором: на точных
    основах recall@5 был 0.64.
    """
    return expression(stems(text))


def expression(parts: list[str]) -> str:
    """То же выражение, но по готовому списку основ.

    Отдельной функцией, потому что поиск подмешивает в запрос написания из
    словаря синонимов (`services/synonyms.py`), а импортировать его сюда
    нельзя — он сам зовёт этот модуль.
    """
    unique = list(dict.fromkeys(parts))
    if not unique:
        return ""
    return " OR ".join(f'"{stem}" *' for stem in unique)
