"""Ответ на вопрос по базе знаний.

Собирает ответ из пяти шагов, и каждый из них умеет закончиться отказом.
Порядок важен: до модели дело доходит последним, и только если есть что ей
показать.

1. базы нет — отвечать нечем;
2. поиск ничего не нашёл — «не нашёл в источниках». **Модель не зовётся**;
3. квота на сутки исчерпана или ключей нет — показываем найденные фрагменты;
4. модель посмотрела и сказала, что во фрагментах ответа нет — молчим тем же
   текстом, что при пустой выдаче поиска. Это второй сторож молчания,
   семантический: первый, лексический, живёт в `kb.py` и судит по словам, а
   не по смыслу;
5. модель отвечает — сшивает найденное в два-три предложения.

**Третий пункт не заглушка, а режим по умолчанию при пустом `.env`.** Цитата
из клинических рекомендаций с названием документа полезна сама по себе, и это
ровно то, чем бот отличается от чата с моделью: он не придумывает, он
показывает, где написано.

**Фрагменты показываются тогда и только тогда, когда о них никто не судил.**
Заголовок над ними обещает, что нашлось именно «по этому вопросу», — а это
утверждение о релевантности. Когда судьи не было (нет ключа, вышла квота,
провайдер не ответил, ответ не разобрался), оно не проверено, но и не
опровергнуто, и цитата с названием документа всё ещё полезна. Когда судья был
и сказал «нет», показать их значит переспорить собственного сторожа и соврать
в заголовке: 17.09 бот так и сделал — на вопрос про цвет кожи ответил тремя
цитатами про кесарево сечение, гипогликемию и срыгивания.

**Сторож чисел.** Каждое число из ответа модели обязано встречаться в
переданных фрагментах или в самом вопросе. Не встречается — ответ
отбрасывается целиком, показываются фрагменты, случай пишется в лог. Это
частный случай правила всего проекта «числа не через LLM»: придуманная
дозировка стоит дороже любого удобства, а заметить её в гладком тексте
невозможно.

**Красных флагов этот модуль не видит, и это правильно.** Их перехватывает
`handlers/alarm`, который стоит выше по списку роутеров: сообщение про судороги
получает фиксированный текст из файла и до Q&A не доходит вовсе. Вторая
проверка здесь была бы второй копией границы безопасности — а копия
расходится с оригиналом молча.
"""

import logging
import re
from dataclasses import dataclass
from pathlib import Path

from bot.services import kb, llm, qa_log

log = logging.getLogger(__name__)

PROMPT = Path(__file__).resolve().parent.parent / "content" / "qa_prompt.md"

# Куски, без которых промпт перестаёт быть тем, что задумано. Проверяются на
# импорте: бот, потерявший запрет выдумывать числа, не должен стартовать
# молча — он выглядел бы работающим
REQUIRED = (
    "ТОЛЬКО",
    "Ни одного числа",
    "Не ставь диагнозов",
    '{"answer"',
)

# Исходы. Строки, а не Enum — как и причины в `llm`
NO_KB = "no_kb"  # базы знаний нет
NOT_FOUND = "not_found"  # не нашли ничего подходящего
EXTRACT = "extract"  # показываем найденное как есть
ANSWERED = "answered"  # модель сшила ответ

# Причины. Отдельно от исходов: исход — что увидел человек, причина — почему.
# Константами стало то, на что смотрят снаружи: `EMPTY` выбирает ветку,
# остальные две утверждаются тестами и грепаются в `qa.log`. Один и тот же
# литерал в трёх местах разошёлся бы молча
EMPTY = "empty"  # модель вернула пустой ответ: во фрагментах его нет
UNGROUNDED = "ungrounded"  # ответ есть, но не опирается ни на один фрагмент
INVENTED = "invented_numbers"  # сторож чисел отбросил ответ целиком
BROKEN = "broken"  # база знаний не открылась

# Потолок на ответ модели. Под ним поедут фрагменты и источники, а у Telegram
# на сообщение 4096 знаков
MAX_ANSWER = 1200


def _load() -> str:
    """Системный промпт из `content/qa_prompt.md`, ниже разделителя.

    Файл читается человеком целиком, а модели уходит только вторая половина:
    первая объясняет, что здесь вообще лежит и что нельзя убирать.
    """
    text = PROMPT.read_text(encoding="utf-8")
    _, sep, body = text.partition("\n---\n")
    if not sep:
        raise ValueError(f"{PROMPT}: нет разделителя `---`, непонятно, что слать модели")
    body = body.strip()
    if not body:
        raise ValueError(f"{PROMPT}: после разделителя пусто")
    for required in REQUIRED:
        if required not in body:
            raise ValueError(f"{PROMPT}: из промпта пропало «{required}»")
    return body


SYSTEM = _load()


@dataclass(frozen=True)
class Result:
    """Чем закончился вопрос. Текст собирает `texts`, здесь только смысл."""

    kind: str
    answer: str  # пусто, если `kind` не `ANSWERED`
    chunks: tuple[kb.Chunk, ...]
    reason: str = ""  # техническая причина, для лога


_NUMBER = re.compile(r"\d+(?:[.,]\d+)?")


def _numbers(text: str) -> set[str]:
    """Числа текста в сравнимом виде.

    Запятая приводится к точке, хвостовые нули у дробных отбрасываются: «6,0»
    и «6.0» — это «6». У целых хвостовые нули не трогаем, иначе «10» стало бы
    «1» и сторож пропускал бы ровно то, ради чего стоит.
    """
    found = set()
    for raw in _NUMBER.findall(text):
        value = raw.replace(",", ".")
        if "." in value:
            value = value.rstrip("0").rstrip(".")
        found.add(value or "0")
    return found


def invented_numbers(answer: str, context: str) -> set[str]:
    """Числа ответа, которых нет ни в источниках, ни в вопросе."""
    return _numbers(answer) - _numbers(context)


def cited(chunks: tuple[kb.Chunk, ...], data: dict | None) -> tuple[kb.Chunk, ...]:
    """Фрагменты, на которые модель сослалась полем `used`.

    Раньше это поле запрашивалось промптом и выбрасывалось. Просить у модели
    то, что не читаешь, — полбеды; беда в том, что под ответом по одному
    фрагменту перечислялись все пять источников, и список источников — главное,
    ради чего этот бот вообще отвечает, — был неправдой.

    Разбор нарочно терпимый: мусор, выход за границы и пустой список означают
    «показываем всё». Отбросить источники по кривому индексу хуже, чем
    показать лишний: в первом случае человек не увидит, откуда взят ответ.
    """
    raw = (data or {}).get("used")
    if not isinstance(raw, list):
        return chunks
    picked: list[kb.Chunk] = []
    for item in raw:
        try:
            index = int(item)
        except (TypeError, ValueError):
            continue
        if 1 <= index <= len(chunks) and chunks[index - 1] not in picked:
            picked.append(chunks[index - 1])
    return tuple(picked) or chunks


def build_user(question: str, chunks: tuple[kb.Chunk, ...]) -> str:
    """Сообщение модели: вопрос и пронумерованные фрагменты."""
    parts = [f"Вопрос: {question}", "", "Фрагменты:"]
    for number, chunk in enumerate(chunks, start=1):
        head = f"{chunk.title}. {chunk.heading}" if chunk.heading else chunk.title
        parts += [f"[{number}] {head}", chunk.text, ""]
    return "\n".join(parts)


async def answer(question: str) -> Result:
    """Ответ на вопрос. Исключений наружу не выпускает.

    Обещание держится здесь, а не надеждой на вызываемых. `llm.ask` свой
    контракт соблюдает, а вот `kb.search` ходит в файл, который между делом
    мог оказаться подменённым или битым: `sqlite3.DatabaseError` оттуда прошёл
    бы насквозь до хендлера, а упавший хендлер — это потерянный навсегда
    апдейт. Битая база — это «базы нет», так и отвечаем.
    """
    try:
        return await _answer(question)
    except Exception:
        log.exception("Не удалось ответить на вопрос")
        return Result(NO_KB, "", (), BROKEN)


async def _answer(question: str) -> Result:
    if not kb.available():
        return Result(NO_KB, "", ())

    chunks = tuple(await kb.search(question))
    if not chunks:
        qa_log.write(event="qa", question=question, outcome=NOT_FOUND, calls=0)
        return Result(NOT_FOUND, "", ())

    # Своя строка в логе, а не общая: `reply` здесь не существует, и приписать
    # ей поля общей записи значило бы либо посчитать квоту дважды, либо не
    # посчитать вовсе
    if qa_log.quota_spent():
        log.warning("Суточная квота обращений к модели исчерпана")
        qa_log.write(event="qa", question=question, outcome=EXTRACT, reason=llm.QUOTA, calls=0)
        return _extract(chunks, llm.QUOTA)

    reply = await llm.ask(SYSTEM, build_user(question, chunks), models=llm.answer_chain())
    result = _decide(question, chunks, reply)
    qa_log.write(
        event="qa",
        question=question,
        outcome=result.kind,
        reason=result.reason,
        # Человеку фрагменты могли и не поехать, а какой именно мусор ворота
        # пропустили в модель — единственное, по чему судят о воротах
        sources=[chunk.source_id for chunk in chunks],
        coverage=round(chunks[0].coverage, 2),
        # Сколько из найденного назвал смысл, а не слова. Без этого числа по
        # логу не отличить «плотный поиск промолчал» от «его не было вовсе»:
        # провайдер векторов может лежать неделю, и снаружи это выглядит как
        # поиск, который просто стал хуже отвечать
        dense=sum(1 for chunk in chunks if chunk.by_meaning),
        model=reply.model,
        detail=reply.detail[:160],
        calls=reply.calls,
        seconds=round(reply.elapsed, 1),
    )
    return result


def _cites_nothing(data: dict) -> bool:
    """Ответ, не опирающийся ни на один фрагмент, — не ответ.

    Промпт просит на «ответа нет» вернуть `{"answer": "", "used": []}`, и
    слабая модель так и делает. Сильная чаще пишет это словами — «в
    предоставленных фрагментах информации нет», — а `used` при этом всё равно
    оставляет пустым. Замерено на семи вопросах: пустой список приходил ровно
    там, где опереться было не на что, и ни разу там, где ответ был.

    Ловить фразу отказа подстрокой было бы хуже вдвойне: формулировок у неё
    бесконечно много, а ложное срабатывание съело бы настоящий ответ. Здесь же
    признак структурный и совпадает с правилом всего проекта — бот не источник
    знания, а сшиватель найденного, и сшивать из ничего ему нечего.

    Пустой список — это утверждение модели, а отсутствующий или битый `used` —
    это её неряшливость: `cited` разбирает его нарочно терпимо, и превращать
    небрежность в молчание нельзя.
    """
    used = data.get("used")
    return isinstance(used, list) and not used


def _decide(question: str, chunks: tuple[kb.Chunk, ...], reply: llm.Answer) -> Result:
    """Вердикт по ответу модели. Отделён от записи в лог намеренно.

    Запись принимает исход аргументом и потому не может разойтись с тем, что
    увидел человек. Так было не всегда: `qa_log.write` стоял выше и писал
    `answered`, едва модель вернула разбираемый JSON, — а ответ после этого
    ещё отбрасывался и пустым, и сторожем чисел. 17.09 оба боевых вопроса
    помечены в логе `answered` при `extract` на экране: единственное полевое
    свидетельство качества врало ровно про тот случай, ради которого его
    читают. Переменной `outcome` с одним `return` внизу было бы мало —
    дописанная ветка со своим `return` развела бы их снова, и снова молча.
    """
    if not reply.ok:
        return _extract(chunks, reply.reason)

    data = reply.data or {}
    text = str(data.get("answer") or "").strip()
    if not text or _cites_nothing(data):
        # Модель посмотрела и ответа во фрагментах не нашла — пустой строкой
        # или фразой об этом, ни на что не сославшись. Молчим:
        # показать их после этого значит переспорить единственного судью
        # релевантности, который у бота есть, и соврать в заголовке «вот что
        # нашлось по этому вопросу». Чанки не кладём в `Result` вовсе —
        # гарантия структурная, а не дисциплинарная: будущему
        # `if result.chunks:` в рендерере нечего будет вытащить
        return Result(NOT_FOUND, "", (), EMPTY if not text else UNGROUNDED)

    # Сторож сверяет со ВСЕМИ найденными фрагментами, а не только с теми, на
    # которые модель сослалась: она их все видела, и число из четвёртого —
    # взятое, а не выдуманное, даже если в `used` его нет
    context = " ".join(chunk.text for chunk in chunks) + " " + question
    invented = invented_numbers(text, context)
    if invented:
        log.warning("Числа не из источника: %s — показываем фрагменты", sorted(invented))
        qa_log.write(event="qa_numbers", question=question, invented=sorted(invented), calls=0)
        return _extract(chunks, INVENTED)

    return Result(ANSWERED, text[:MAX_ANSWER], cited(chunks, reply.data))


def _extract(chunks: tuple[kb.Chunk, ...], reason: str) -> Result:
    """Показать найденное как есть. В лог не пишет — пишет вызывающий.

    Раньше писала иногда, по флагу `logged`. Два поведения под одним именем —
    и есть та щель, в которую уехала правдивость лога.
    """
    return Result(EXTRACT, "", chunks, reason)
