"""Числительные словами → цифры. Один проход по расшифровке голосового.

**Зачем это нужно, и почему это не украшение.** `redflags.find_temperatures`
ищет в сообщении **цифры**: `NUMBER.finditer` по нормализованному тексту. Whisper
на русском сплошь и рядом пишет «тридцать девять и пять» словами — и тогда
«температура тридцать девять» не поднимает ничего, хотя тот же текст, набранный
цифрами, поднимает тревогу. Это пропуск в опасную сторону, и он появляется
ровно вместе с голосовым каналом: до него весь текст приходил с клавиатуры, где
числа пишут цифрами.

**Правило про язык, а не про медицину.** «Тридцать семь и пять» — это 37.5
независимо от того, о чём речь, поэтому таблица слов живёт в коде. Пороги
остаются в `redflags.yaml`: здесь нет ни одного числа, имеющего смысл нормы.

**Преобразование делается один раз, сразу после расшифровки, и дальше везде
живёт один текст** — он же в эхе на карточке, он же в триаже, он же в промпте
модели. Это требование `morph`: нормализация одна на проект, иначе поиск и
триаж начинают зависеть от того, через какую дверь вошёл текст. И это
единственный способ не спрятать ошибку этого модуля: человек видит на карточке
именно то, что пошло в разбор, а не другую версию той же фразы.

Нормализация слова для поиска в таблице берётся та же, что в триаже, —
`redflags.normalize`. Своя расходилась бы с ней молча, а разница «ё/е» здесь
решает, найдётся слово в таблице или нет.

**Составное число собирается только по убыванию разрядов.** «Тридцать девять» —
это 39, а «три сорок» числом не является вовсе: так по-русски не говорят, это
время. Поэтому 3 и 40 остаются двумя числами, и «в три сорок» превращается в
«в 3 40» — разбирать это дальше дело модели, а не наше. Складывать всё подряд
было бы куда хуже: «в три сорок» дало бы 43.
"""

import re

from bot.services.redflags import normalize

# Разряды. Число, собранное из нескольких слов, обязано идти по убыванию:
# сотни, потом десятки, потом единицы. Второй десяток («тринадцать») занимает
# сразу оба младших разряда, поэтому у него тот же разряд, что у десятков
UNIT, TEN, HUNDRED = 1, 2, 3

_UNITS = {
    "ноль": 0, "нуль": 0,
    "один": 1, "одна": 1, "одно": 1, "одного": 1, "одну": 1,
    "два": 2, "две": 2, "двух": 2,
    "три": 3, "трех": 3,
    "четыре": 4, "четырех": 4,
    "пять": 5, "пяти": 5,
    "шесть": 6, "шести": 6,
    "семь": 7, "семи": 7,
    "восемь": 8, "восьми": 8,
    "девять": 9, "девяти": 9,
}

_TEENS = {
    "десять": 10, "десяти": 10,
    "одиннадцать": 11, "одиннадцати": 11,
    "двенадцать": 12, "двенадцати": 12,
    "тринадцать": 13, "тринадцати": 13,
    "четырнадцать": 14, "четырнадцати": 14,
    "пятнадцать": 15, "пятнадцати": 15,
    "шестнадцать": 16, "шестнадцати": 16,
    "семнадцать": 17, "семнадцати": 17,
    "восемнадцать": 18, "восемнадцати": 18,
    "девятнадцать": 19, "девятнадцати": 19,
}

_TENS = {
    "двадцать": 20, "двадцати": 20,
    "тридцать": 30, "тридцати": 30,
    "сорок": 40, "сорока": 40,
    "пятьдесят": 50, "пятидесяти": 50,
    "шестьдесят": 60, "шестидесяти": 60,
    "семьдесят": 70, "семидесяти": 70,
    "восемьдесят": 80, "восьмидесяти": 80,
    "девяносто": 90, "девяноста": 90,
}

_HUNDREDS = {
    "сто": 100, "ста": 100,
    "двести": 200, "двухсот": 200,
    "триста": 300, "трехсот": 300,
    "четыреста": 400, "четырехсот": 400,
    "пятьсот": 500, "пятисот": 500,
    "шестьсот": 600, "шестисот": 600,
    "семьсот": 700, "семисот": 700,
    "восемьсот": 800, "восьмисот": 800,
    "девятьсот": 900, "девятисот": 900,
}

# Множитель, а не разряд: он умножает то, что набралось до него, и открывает
# новое число. «Три тысячи восемьсот» — это 3800, вес в граммах
_THOUSANDS = frozenset({"тысяча", "тысячи", "тысяч", "тысячу"})

# «Полтора» — само себе число и ни с чем не складывается. Здесь оно не для
# полноты таблицы: на «поспала полтора часа» модель, не увидев числа, вернула
# длительность `null`, то есть законченный сон превратился в идущий таймер.
# Ошибка молчаливая и дорогая — открытый таймер потом закроет тикер с пометкой
# «приблизительно», и в отчёте педиатру это выглядит измеренным
_HALVES = {"полтора": 1.5, "полторы": 1.5, "полутора": 1.5}

# Слово — буквы и цифры подряд, как в `morph._WORD`. Дефис границей: «во-первых»
# двумя токенами полезнее, чем одним
_WORD = re.compile(r"[0-9A-Za-zА-Яа-яЁё]+")

# Дробная часть словами: «тридцать семь и пять» — это 37.5. Слева требуется
# число не меньше десяти, и это не перестраховка: «три и пять» по-русски не
# дробь, а перечисление, а «тридцать шесть и шесть» — именно температура.
# Порог про язык, не про медицину: десятичную часть словами называют у больших
# чисел, а у маленьких перечисляют
_DECIMAL_MIN_WHOLE = 10


def _rank(word: str) -> int | None:
    """Разряд слова, или None — слово не числительное."""
    if word in _HUNDREDS:
        return HUNDRED
    if word in _TENS or word in _TEENS:
        return TEN
    if word in _UNITS:
        return UNIT
    return None


def _value(word: str) -> int:
    for table in (_HUNDREDS, _TENS, _TEENS, _UNITS):
        if word in table:
            return table[word]
    raise KeyError(word)  # pragma: no cover — звать только после `_rank`


class _Run:
    """Одно число, собранное из подряд идущих слов, и его место в тексте."""

    __slots__ = ("start", "end", "value", "words")

    def __init__(self, start: int, end: int, value: float, words: int) -> None:
        self.start = start
        self.end = end
        self.value = value
        self.words = words


def _runs(text: str) -> list[_Run]:
    """Числа, названные словами, в порядке появления."""
    found: list[_Run] = []
    total = 0  # набранное до «тысяч»
    part = 0  # набранное в текущем разрядном ряду
    last_rank = HUNDRED + 1  # следующее слово обязано быть младше
    start = end = words = 0

    def flush() -> None:
        nonlocal total, part, last_rank, words
        if words:
            found.append(_Run(start, end, total + part, words))
        total = part = words = 0
        last_rank = HUNDRED + 1

    for match in _WORD.finditer(text):
        word = normalize(match.group())

        if word in _THOUSANDS and words:
            # «Три тысячи» — умножаем набранное и открываем новый ряд.
            # Без набранного («тысяча грамм») слово само за число не считаем:
            # оно чаще единица измерения, чем количество
            total = (total + part) * 1000
            part = 0
            last_rank = HUNDRED + 1
            end = match.end()
            words += 1
            continue

        if word in _HALVES:
            # Готовое число: ни с чем не складывается и ничем не продолжается
            flush()
            found.append(_Run(match.start(), match.end(), _HALVES[word], 1))
            continue

        rank = _rank(word)
        if rank is None:
            flush()
            continue

        if rank >= last_rank:
            # Разряд не убыл: «три сорок» — это не число, а два числа подряд
            flush()

        if not words:
            start = match.start()
        part += _value(word)
        last_rank = rank
        end = match.end()
        words += 1

    flush()
    return found


def _joins_as_decimal(text: str, left: _Run, right: _Run) -> bool:
    """Между числами стоит только «и», и они читаются как одна дробь."""
    if left.value < _DECIMAL_MIN_WHOLE or not 1 <= right.value <= 9:
        return False
    if right.words != 1:
        return False
    return normalize(text[left.end : right.start]).strip() == "и"


def digits(text: str) -> str:
    """Расшифровка, в которой числительные словами заменены цифрами.

    Текст без числительных возвращается в точности как был — ни один знак не
    меняется. Уже написанное цифрами не трогается вовсе: заменяются только
    слова.
    """
    runs = _runs(text)
    if not runs:
        return text

    pieces: list[str] = []
    cursor = 0
    index = 0
    while index < len(runs):
        run = runs[index]
        following = runs[index + 1] if index + 1 < len(runs) else None
        if following is not None and _joins_as_decimal(text, run, following):
            written = f"{run.value:g}.{following.value:g}"
            stop = following.end
            index += 2
        else:
            written = f"{run.value:g}"
            stop = run.end
            index += 1
        pieces.append(text[cursor : run.start])
        pieces.append(written)
        cursor = stop

    pieces.append(text[cursor:])
    return "".join(pieces)
