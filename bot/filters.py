"""Фильтры области видимости.

Бот живёт только в семейном чате. В личке записи были бы личными, и второй
родитель их не увидел бы — а весь смысл в том, чтобы оба видели одно и то же и
не спрашивали друг у друга «ты её кормил?».
"""

from aiogram import F

IN_GROUP = F.chat.type.in_({"group", "supergroup"})

# То же для колбэков: у CallbackQuery чат лежит внутри сообщения
IN_GROUP_CB = F.message.chat.type.in_({"group", "supergroup"})

# Личка: семьи там нет, поэтому вся работа сводится к вежливому отказу
IN_PRIVATE = F.chat.type == "private"
