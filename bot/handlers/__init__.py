"""Порядок роутеров значим.

`measure` стоит последним, потому что в нём висит `F.text` — обработчик голого
числа. Он не должен перехватывать ни команды, ни шаги мастера `/baby`, а
aiogram отдаёт апдейт первому роутеру, чей фильтр сошёлся.

`common` первым: в нём отказ для лички, и он обязан сработать раньше всего
остального, что могло бы попытаться достать из апдейта несуществующую семью.

`alarm` вторым, и это не вкусовщина. Если мама пишет про симптом, находясь
посреди мастера `/baby`, ответить надо про симптом, а не записать его как имя
ребёнка. Это же и граница для Q&A: `qa` стоит ниже, поэтому сообщение с
тревожным признаком получает фиксированный текст из файла и до модели не
доходит вовсе.

`qa` предпоследним, сразу перед `measure`. Ниже `alarm` — по границе выше;
выше `measure` — потому что иначе апдейт до него не дойдёт: там голый `F.text`.
Своё голое число `qa` при этом не съедает: его обработчик висит на фильтре
«ждём вопрос», и не совпав, пропускает апдейт дальше нетронутым.

`remind` встал между `export` и `track` — то есть ниже `alarm` и выше
`measure`. Обе границы он не двигает и двигать не может: в нём нет ни одного
текстового обработчика, только команда и кнопки. Ниже `alarm` он стоит не по
необходимости, а по правилу: граница безопасности не двигается ни для кого,
включая безобидный экран настроек.
"""

