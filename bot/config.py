"""Настройки бота. Формат и идиомы — как в Family_planer.

Две идиомы, которые стоит помнить, читая этот файл:

* `0` = функция выключена (`backup_keep`, `llm_daily_limit`);
* пустая строка = «работаем напрямую / без вендора».

Синглтон `settings` создаётся **на импорте**, поэтому бот и тесты запускаются
только из корня проекта: иначе `.env` не найдётся и `bot_token` уронит импорт
с `ValidationError`. Это осознанная цена за один источник правды о настройках.
"""

from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )

    bot_token: str
    db_path: Path = Path("data/baby.db")

    # --- Владелец ---------------------------------------------------------
    # `chat_id` семьи владельца. Нужен ровно одному месту — `/backup`, которая
    # шлёт в чат **весь** файл базы, а база одна на все семьи. Пока семья одна,
    # это офсайт-хранилище; со второй та же команда, набранная в чужой группе,
    # отдала бы туда дневник чужого ребёнка.
    #
    # `0` = выключено, и это не поблажка, а прежнее поведение: у того, кто
    # держит бота для себя одного, чужих чатов нет вовсе
    owner_chat_id: int = 0

    tz_default: str = "Europe/Moscow"
    tick_seconds: int = 60

    # --- Напоминания и догонка пропущенного -------------------------------
    # Три ступени в `ticker.classify_lateness`. Для бота о младенце они важнее,
    # чем в планировщике: ПК уходит в сон, а напоминания о кормлении идут раз в
    # 2–3 часа. Без сворачивания в сводку после пробуждения семья получила бы
    # очередь из восьми «пора кормить» в одну секунду
    late_silent_min: int = 10
    late_summary_hours: int = 12

    # --- Панель -----------------------------------------------------------
    # Панель — главный экран бота, она обновляется на каждый тап. Дебаунс
    # склеивает серию правок в одно редактирование. Перенос вниз теперь только
    # явный; panel_max_messages сохранён для совместимости старых настроек.
    panel_max_messages: int = 15
    panel_debounce_seconds: float = 0.15

    # --- Трекер -----------------------------------------------------------
    # Через сколько часов незакрытый таймер кормления или сна считать забытым.
    # Закрывать надо обязательно: открытый таймер ломает всю статистику суток,
    # а забыть вторую кнопку в три часа ночи — норма, а не исключение.
    # Закрытое тикером событие помечается `estimated`, чтобы в отчёте для
    # педиатра было видно, что это не измерение, а догадка
    open_timer_max_hours: float = 4.0

    # Недельный дайджест: день недели (0 = понедельник) и локальное время
    digest_dow: int = 0
    digest_time: str = "10:00"

    # --- База знаний ------------------------------------------------------
    # Отдельный файл, а не таблица в `baby.db`, и это не мелочь. База знаний —
    # артефакт сборки: она целиком восстанавливается запуском `kb/build_kb.py`,
    # тогда как вес и кормления за первый год не восстанавливаются ничем.
    # Смешав их в одном файле, мы бы каждую ночь клали десятки мегабайт
    # пересобираемого текста в снимок и отправляли их же в чат по `/backup`.
    kb_path: Path = Path("data/kb.db")

    # Сколько фрагментов уходит в ответ и в промпт. Больше пяти читать никто
    # не станет, а модели лишние фрагменты дают лишний повод их перепутать
    kb_top_k: int = 5

    # Доля значимых слов вопроса, которую обязан покрыть найденный фрагмент,
    # иначе считаем, что не нашли. Без этого порога поиск отвечает всегда:
    # запрос разворачивается в ИЛИ по основам, и слово «сколько» вытащит
    # случайный кусок любого документа. «Не нашёл» — законный ответ, а
    # придуманный по мотивам случайного абзаца — нет.
    #
    # Значимыми считаются не все слова: основы, встречающиеся чаще чем в
    # `kb_stopword_df` доле фрагментов, отбрасываются как служебные
    kb_min_coverage: float = 0.5
    kb_stopword_df: float = 0.25

    # --- Плотный поиск ----------------------------------------------------
    # Модель, которой считается смысл фрагмента и вопроса. Векторы двух разных
    # моделей несравнимы, поэтому смена этой строки требует пересборки базы:
    # `kb.db` помнит, чем её посчитали, и при несовпадении плотный поиск
    # выключается сам. Пусто = плотного поиска нет, поиск лексический, как до
    # 19.09.2026
    embed_model: str = "baai/bge-m3"

    # Ключ и прокси отдельными строками, хотя вендор тот же, что у ответов.
    # Пусто = берём ключ и прокси OpenRouter. Смысл отдельной строки не в
    # втором секрете, а в возможности выключить плотный поиск, не трогая Q&A
    embed_key: str = ""
    embed_proxy: str = ""

    # По сколько текстов уходит в один запрос при сборке базы. Две тысячи
    # фрагментов по одному — это две тысячи запросов и верный 429; пачками по
    # 64 их тридцать три
    embed_batch: int = 64

    # Пол по косинусу для плотной выдачи. Плотный поиск молчать не умеет —
    # ближайший по смыслу кусок найдётся и для вопроса про биткоин, — и это
    # единственная ручка, которой его можно приглушить.
    #
    # Значение выбирается замером, а не на глаз: у прошлой такой ручки
    # (idf-взвешенное покрытие) между соседними значениями recall прыгал на
    # тринадцать пунктов, и её за это отклонили. Кривая по этой лежит в
    # `docs/TASKS.md`. 0 = пола нет, молчание держат ворота вопроса и сторож
    # в `services/qa.py`
    kb_min_similarity: float = 0.50

    # --- LLM --------------------------------------------------------------
    # Цепочка моделей, через запятую, в порядке перебора. Каждая запись —
    # `вендор:модель`; без префикса подразумевается `openrouter`.
    #
    # Смысл списка — независимость отказов, а не качество. Урок Family_planer:
    # 01.09.2026 разбор встал целиком на 401 от единственного провайдера
    # бесплатной модели. Поэтому соседние звенья берём у разных вендоров
    llm_models: str = ""
    openrouter_key: str = ""
    groq_key: str = ""

    # Модель для медицинских ответов по базе знаний. Отдельно от `llm_models`,
    # потому что задачи разные по цене ошибки: разобрать «покормили 20 минут»
    # может кто угодно, а отвечать на вопрос о ребёнке — нет.
    # Пусто = берём первую из `llm_models`
    llm_answer_models: str = ""

    # Сколько запросов к моделям в сутки себе позволяем — на всю цепочку разом.
    # Считаем сами, по `data/qa.log`: провайдер о приближении к лимиту не
    # предупреждает, он просто начинает отвечать 429. 0 = не ограничивать
    llm_daily_limit: int = 300

    # --- Расшифровка голосовых -------------------------------------------
    # Whisper-совместимый эндпоинт Groq принимает ogg/opus Telegram как есть,
    # поэтому ffmpeg проекту не нужен
    stt_key: str = ""
    stt_model: str = "whisper-large-v3-turbo"
    stt_url: str = "https://api.groq.com/openai/v1/audio/transcriptions"
    voice_max_seconds: int = 120

    # --- Бэкапы -----------------------------------------------------------
    # Сколько снимков держать в `data/backups/`. 0 = ежедневный снимок выключен,
    # но `/backup` работает.
    #
    # Здесь это важнее, чем в планировщике: вес и кормления за первый год
    # ребёнка невосстановимы. Держим две недели, а не неделю
    backup_keep: int = 14

    # --- Прокси -----------------------------------------------------------
    # Пустое значение = работаем напрямую. Прокси нужен из-за недоступности
    # api.telegram.org из России; порт тот же, что у Family_planer (Karing)
    telegram_proxy: str = ""
    openrouter_proxy: str = ""
    groq_proxy: str = ""
    stt_proxy: str = ""

    @property
    def db_url(self) -> str:
        return f"sqlite+aiosqlite:///{self.db_path}"


settings = Settings()  # type: ignore[call-arg]
